class VerbTimelineItem {
  final int id;
  final String baseVerb;
  final String meaningMl;
  final Map<String, String>? meanings;
  final String past;
  final String present;
  final String future;
  final String pastSentence;
  final String presentSentence;
  final String futureSentence;
  final String rhythmChant;
  final String grammarTrapMl;
  final Map<String, String>? grammarTraps;
  final String pastLabel;
  final String presentLabel;
  final String futureLabel;
  final Map<String, String>? pastSubtitles;
  final Map<String, String>? presentSubtitles;
  final Map<String, String>? futureSubtitles;
  final String tenseCategory;

  const VerbTimelineItem({
    required this.id,
    required this.baseVerb,
    required this.meaningMl,
    this.meanings,
    required this.past,
    required this.present,
    required this.future,
    required this.pastSentence,
    required this.presentSentence,
    required this.futureSentence,
    required this.rhythmChant,
    required this.grammarTrapMl,
    this.grammarTraps,
    this.pastLabel = 'PAST',
    this.presentLabel = 'PRESENT',
    this.futureLabel = 'FUTURE',
    this.pastSubtitles,
    this.presentSubtitles,
    this.futureSubtitles,
    this.tenseCategory = 'Simple',
  });

  String getLocalizedMeaning([String? lang]) {
    final language = lang ?? PocketLanguageService.currentLanguage;
    if (meanings != null && meanings!.isNotEmpty) {
      return PocketDayCurriculumService.getLocalizedText(meanings, lang: language, fallback: meaningMl);
    }
    return PocketVerbLocalizationService.getMeaning(baseVerb, lang: language, fallback: meaningMl);
  }

  String getLocalizedGrammarTrap([String? lang]) {
    final language = lang ?? PocketLanguageService.currentLanguage;
    if (grammarTraps != null && grammarTraps!.isNotEmpty) {
      return PocketDayCurriculumService.getLocalizedText(grammarTraps, lang: language, fallback: grammarTrapMl);
    }
    return PocketVerbLocalizationService.getGrammarTrap(
      baseVerb: baseVerb,
      past: past,
      lang: language,
      fallback: grammarTrapMl,
    );
  }

  String getLocalizedPastSubtitle([String? lang]) {
    final language = lang ?? PocketLanguageService.currentLanguage;
    if (pastSubtitles != null && pastSubtitles!.isNotEmpty) {
      return PocketDayCurriculumService.getLocalizedText(pastSubtitles, lang: language);
    }
    return PocketVerbLocalizationService.getPastSubtitle(tenseCategory, lang: language);
  }

  String getLocalizedPresentSubtitle([String? lang]) {
    final language = lang ?? PocketLanguageService.currentLanguage;
    if (presentSubtitles != null && presentSubtitles!.isNotEmpty) {
      return PocketDayCurriculumService.getLocalizedText(presentSubtitles, lang: language);
    }
    return PocketVerbLocalizationService.getPresentSubtitle(tenseCategory, lang: language);
  }

  String getLocalizedFutureSubtitle([String? lang]) {
    final language = lang ?? PocketLanguageService.currentLanguage;
    if (futureSubtitles != null && futureSubtitles!.isNotEmpty) {
      return PocketDayCurriculumService.getLocalizedText(futureSubtitles, lang: language);
    }
    return PocketVerbLocalizationService.getFutureSubtitle(tenseCategory, lang: language);
  }
}

