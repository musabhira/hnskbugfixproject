/// 💬 Useful English Phrase Item
class UsefulPhraseItem {
  final String phraseEn;
  final String meaningMl;
  final String meaningTa;
  final String meaningHi;
  final String meaningKn;
  final String anchorWord;
  final String? tip;

  const UsefulPhraseItem({
    required this.phraseEn,
    required this.meaningMl,
    required this.meaningTa,
    required this.meaningHi,
    required this.meaningKn,
    required this.anchorWord,
    this.tip,
  });

  /// Returns localized meaning according to app language
  String getLocalizedMeaning() {
    return PocketLanguageService.localize(
      en: phraseEn,
      ml: meaningMl,
      ta: meaningTa,
      hi: meaningHi,
      kn: meaningKn,
    );
  }

  /// Words broken down for tile assembly bank
  List<String> get words => phraseEn.trim().split(RegExp(r'\s+'));
}

