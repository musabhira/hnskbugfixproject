class PocketKidsCurriculumAdapter {
  static SentenceChallengeRound _buildKidRound({
    required int id,
    required String sentence,
    required String translationMl,
    required String hint,
  }) {
    final tokens = sentence.split(' ').where((w) => w.isNotEmpty).toList();
    final tiles = <SentenceTileData>[];
    for (int i = 0; i < tokens.length; i++) {
      final t = tokens[i];
      final lower = t.toLowerCase();
      SentenceTileColor color;
      if (['i', 'you', 'we', 'they', 'he', 'she', 'it', 'my', 'your', 'our', 'his', 'her'].contains(lower)) {
        color = SentenceTileColor.green;
      } else if (['is', 'am', 'are', 'can', 'see', 'love', 'like', 'have', 'has', 'play', 'run', 'jump', 'sing', 'eat', 'sleep'].contains(lower)) {
        color = SentenceTileColor.magenta;
      } else {
        color = SentenceTileColor.cyan;
      }
      tiles.add(SentenceTileData(
        id: 'kid_r${id}_${t}_$i',
        word: t,
        colorType: color,
      ));
    }
    return SentenceChallengeRound(
      id: id,
      sentence: sentence,
      translationMl: translationMl,
      tiles: tiles,
      hint: hint,
    );
  }

