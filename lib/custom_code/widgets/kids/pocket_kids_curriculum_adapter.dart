  static List<EssentialWordModel> getKidsSpellingWordsForDay(int day) {
    final clampedDay = day.clamp(1, 90);
    const palette = [
      Color(0xFF10B981), // Emerald Green
      Color(0xFF38BDF8), // Sky Blue
      Color(0xFFF59E0B), // Amber Yellow
      Color(0xFFEC4899), // Pink
      Color(0xFFA855F7), // Purple
      Color(0xFFF97316), // Coral Orange
    ];
    final rawWords = _masterWords[clampedDay] ?? _masterWords[1]!;
    return List.generate(rawWords.length, (idx) {
      final w = rawWords[idx];
      return EssentialWordModel(
        word: w['word']!,
        phonetic: w['ph']!,
        color: palette[idx % palette.length],
        meaningMl: w['ml']!,
        exampleSentence: w['ex']!,
      );
    });
  }
