  /// 🧩 90-Day Progressive Kids Sentence Builder Database (Zero Duplication!)
  static List<SentenceChallengeRound> getKidsSentencesForDay(int day) {
    final clampedDay = day.clamp(1, 90);
    final rawList = _masterSentences[clampedDay] ?? _masterSentences[1]!;
    return List.generate(rawList.length, (idx) {
      final item = rawList[idx];
      return _buildKidRound(
        id: idx + 1,
        sentence: item['en']!,
        translationMl: item['ml']!,
        hint: item['hint']!,
      );
    });
  }

