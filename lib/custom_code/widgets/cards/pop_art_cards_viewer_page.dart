    if (_selectedFilter == 'Female') {
      return kPopArt180Cards.where((c) => !c.isMale).toList();
    } else if (_selectedFilter == 'Male') {
      return kPopArt180Cards.where((c) => c.isMale).toList();
    }
    return kPopArt180Cards;
  }

