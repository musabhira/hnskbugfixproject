  final int initialCardIndex;
  const PopArtAvatarCardsViewerPage({super.key, this.initialCardIndex = 0});

  static Future<void> open(BuildContext context, {int initialIndex = 0}) {
    return Navigator.push(
      context,
      MaterialPageRoute(
        builder: (_) => PopArtAvatarCardsViewerPage(initialCardIndex: initialIndex),
      ),
    );
  }

  @override
  State<PopArtAvatarCardsViewerPage> createState() => _PopArtAvatarCardsViewerPageState();
}

